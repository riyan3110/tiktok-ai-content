const OpenAI = require('openai');
const config = require('../config');

const MAX_FACTS = 36;
const MAX_VERIFY_ATTEMPTS = 2;
const TOPIC_STOPWORDS = new Set(['yang', 'dan', 'atau', 'dari', 'untuk', 'dengan', 'tentang', 'cara', 'adalah', 'pada', 'itu', 'ini', 'sebagai']);
const BOILERPLATE = /(?:cookie|privacy|privasi|terms of use|syarat dan ketentuan|copyright|hak cipta|newsletter|subscribe|follow\s+(?:me|us)|ikuti kami|sign in|login|contact us|hubungi kami|(?:author|writer|contributor)\s+(?:bio|profile)|about the author|tentang penulis|voice experience.*generated by ai|audio.*generated by ai|^(?:by|oleh|written by|ditulis oleh|edited by|disunting oleh)\s+[\p{L}.' -]{3,80}[.!]?$)/iu;
const FACT_VERBS = /\b(?:adalah|merupakan|memiliki|menggunakan|meluncurkan|menawarkan|menyebut|mengatakan|menurut|menunjukkan|mencapai|meningkat|menurun|berasal|didirikan|bekerja|mampu|dapat|bisa|membantu|menghasilkan|mengubah|menjadi|termasuk|tersedia|dirilis|dikembangkan|mencatat|menilai|menganggap|memungkinkan)\b/i;
const NON_FACTUAL_START = /^(?:coba|baca|lihat|simpan|cek|pilih|mulai|bandingkan|pertimbangkan|fokus|jelajahi|ikuti|bagikan|tanyakan|pikirkan|perhatikan)\b/i;

const words = value => String(value || '').trim().split(/\s+/).filter(Boolean);
const normalize = value => String(value || '')
  .toLocaleLowerCase('id-ID')
  .replace(/&nbsp;/gi, ' ')
  .replace(/[^a-z0-9%\s]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();
const tokens = value => new Set(normalize(value).split(' ').filter(Boolean));

function topicTokens(value) {
  return [...tokens(value)].filter(token => (token.length > 2 || token === 'ai') && !TOPIC_STOPWORDS.has(token));
}

function evidenceCandidates(text) {
  const sentences = String(text || '').replace(/\s+/g, ' ').trim().split(/(?<=[.!?])\s+/);
  return sentences.flatMap(sentence => {
    const clean = sentence.trim();
    if (!clean || BOILERPLATE.test(clean)) return [];
    if (words(clean).length >= 4 && words(clean).length <= 32) return [clean];
    return clean.split(/(?<=[;:])\s+|\s+[—–]\s+|,\s+(?=(?:while|but|however|sedangkan|sementara|tetapi|namun|dan)\s+)/i)
      .map(value => value.trim())
      .filter(value => words(value).length >= 4 && words(value).length <= 32 && !BOILERPLATE.test(value));
  });
}

function extractFactBank(sources = [], topic = '') {
  const wanted = topicTokens(topic);
  const perSource = sources.map((source, sourceIndex) => {
    const seen = new Set();
    return evidenceCandidates(source?.text).map((evidence, order) => {
      const normalized = normalize(evidence);
      if (!normalized || seen.has(normalized)) return null;
      seen.add(normalized);
      const evidenceTokens = tokens(evidence);
      const overlap = wanted.filter(token => evidenceTokens.has(token)).length;
      return {
        sourceId: `source-${sourceIndex + 1}`,
        evidence,
        score: overlap * 100 - order,
        order
      };
    }).filter(Boolean).sort((a, b) => b.score - a.score || a.order - b.order);
  });

  const bank = [];
  const seenEvidence = new Set();
  while (bank.length < MAX_FACTS && perSource.some(queue => queue.length)) {
    for (const queue of perSource) {
      const fact = queue.shift();
      if (!fact) continue;
      const key = normalize(fact.evidence);
      if (!seenEvidence.has(key)) {
        seenEvidence.add(key);
        bank.push({ sourceId: fact.sourceId, evidence: fact.evidence });
      }
      if (bank.length >= MAX_FACTS) break;
    }
  }
  return bank;
}

function numericTokens(value) {
  return String(value || '').match(/\b\d+(?:[.,]\d+)?%?\b/g) || [];
}

function isQuestion(value) {
  return /\?\s*$/.test(String(value || '').trim());
}

function requiresEvidence(value, section = '', kind = 'body') {
  const text = String(value || '').trim();
  if (!text) return false;
  if (numericTokens(text).length) return true;
  if (FACT_VERBS.test(text)) return true;
  if (/\b(?:rp|usd|dolar|persen|tahun|bulan|hari|jam|menit|juta|miliar|triliun)\b/i.test(text)) return true;
  if (NON_FACTUAL_START.test(text) && !FACT_VERBS.test(text)) return false;
  if (isQuestion(text) && !FACT_VERBS.test(text)) return false;
  if (/^(?:PEMBUKA|TRANSISI|PENUTUP|CTA)$/i.test(String(section || '').trim())) return false;
  return kind === 'body' || kind === 'point' || /^(?:FAKTA|PENJELASAN|MASALAH|SOLUSI)$/i.test(String(section || '').trim());
}

function slideFields(slide, slideIndex) {
  const fields = [
    { key: `slide:${slideIndex}:title`, value: String(slide?.title || '').trim(), kind: 'title' },
    { key: `slide:${slideIndex}:body`, value: String(slide?.body || '').trim(), kind: 'body' }
  ];
  (slide?.points || []).forEach((point, pointIndex) => fields.push({
    key: `slide:${slideIndex}:point:${pointIndex}`,
    value: String(point || '').trim(),
    kind: 'point'
  }));
  return fields;
}

function sourceMap(sources = []) {
  return new Map(sources.map((source, index) => [`source-${index + 1}`, normalize(source?.text || '')]));
}

function normalizeClaims(slides = []) {
  return slides.flatMap((slide, slideIndex) => (Array.isArray(slide?.claims) ? slide.claims : []).map(claim => ({
    slideIndex,
    field: String(claim?.field || '').trim(),
    text: String(claim?.text || '').trim(),
    sourceId: String(claim?.sourceId || '').trim(),
    evidence: String(claim?.evidence || '').trim()
  })));
}

function validateVerifiedContent(base, candidate, { contentService, format, manualTopic, sources }) {
  const errors = [];
  if (!candidate || !Array.isArray(candidate.slides)) return ['Verifier tidak mengembalikan slides.'];
  if (candidate.slides.length !== base.slides.length) errors.push('Verifier mengubah jumlah slide.');

  const requestedNorm = normalize(manualTopic);
  const maps = sourceMap(sources);
  candidate.slides.forEach((slide, index) => {
    const baseSlide = base.slides[index];
    if (!baseSlide) return;
    if (String(slide.section || '').trim() !== String(baseSlide.section || '').trim()) errors.push(`Slide ${index + 1}: section berubah.`);
    if (!String(slide.title || '').trim()) errors.push(`Slide ${index + 1}: title kosong.`);
    if (!String(slide.body || '').trim() && !(slide.points || []).length) errors.push(`Slide ${index + 1}: tidak memiliki isi bermakna.`);
    if (requestedNorm && normalize(slide.title) === requestedNorm) errors.push(`Slide ${index + 1}: requestedTopic dipakai mentah sebagai judul.`);
    const rendered = `${slide.title || ''} ${slide.body || ''} ${(slide.points || []).join(' ')}`;
    if (/lanjut\s+baca\s+tentang/i.test(rendered)) errors.push(`Slide ${index + 1}: memakai filler "Lanjut baca tentang".`);
    if (BOILERPLATE.test(rendered)) errors.push(`Slide ${index + 1}: metadata/boilerplate website masuk ke konten.`);
  });

  const claims = normalizeClaims(candidate.slides);
  const claimByField = new Map();
  for (const claim of claims) {
    if (!claim.field || !claim.text || !claim.sourceId || !claim.evidence) {
      errors.push('Claim verifier tidak lengkap.');
      continue;
    }
    if (!maps.has(claim.sourceId)) {
      errors.push(`Claim memakai sourceId yang tidak tersedia: ${claim.sourceId}.`);
      continue;
    }
    const evidenceNorm = normalize(claim.evidence);
    if (!evidenceNorm || !maps.get(claim.sourceId).includes(evidenceNorm)) {
      errors.push(`Evidence tidak ditemukan pada ${claim.sourceId}.`);
      continue;
    }
    if (words(claim.evidence).length < 4 || words(claim.evidence).length > 32) errors.push('Evidence harus 4–32 kata.');
    const claimNumbers = numericTokens(claim.text);
    const evidenceNumbers = new Set(numericTokens(claim.evidence));
    if (!claimNumbers.every(number => evidenceNumbers.has(number))) errors.push(`Angka pada claim tidak didukung evidence: ${claim.text}.`);
    if (claimByField.has(claim.field)) errors.push(`Field ${claim.field} memiliki claim ganda.`);
    claimByField.set(claim.field, claim);
  }

  candidate.slides.forEach((slide, slideIndex) => {
    for (const field of slideFields(slide, slideIndex)) {
      if (!field.value) continue;
      const needsEvidence = requiresEvidence(field.value, slide.section, field.kind);
      const claim = claimByField.get(field.key);
      if (needsEvidence && !claim) errors.push(`${field.key}: klaim faktual tidak memiliki evidence.`);
      if (claim && normalize(claim.text) !== normalize(field.value)) errors.push(`${field.key}: claim.text tidak sama dengan copy field.`);
    }
  });

  const verified = {
    ...base,
    slides: candidate.slides,
    verificationStatus: 'source_based',
    unsupportedClaims: []
  };
  const first = verified.slides[0];
  const informative = verified.slides.find(slide => String(slide.body || '').trim() || (slide.points || []).length) || first;
  const last = verified.slides.at(-1);
  verified.hook = String(first?.title || base.hook || '').trim();
  verified.body = String(informative?.body || informative?.points?.join(' ') || base.body || '').trim();
  verified.caption = verified.body;
  verified.cta = String(last?.title || base.cta || '').trim();

  if (contentService?.validateContent) {
    errors.push(...contentService.validateContent(verified, { format, manualTopic, validateCopy: false }));
  }
  return { errors: [...new Set(errors)], content: verified };
}

function verifierPrompt({ base, bank, topic, format, errors = [] }) {
  return `Anda adalah FILTER/VERIFIER fakta untuk carousel Indonesia. Anda BUKAN pembuat struktur carousel baru.

TOPIK REFERENSI: ${JSON.stringify(topic || '')}
FORMAT: ${JSON.stringify(format || '')}

ATURAN WAJIB:
- Pertahankan JUMLAH slide, URUTAN slide, dan SECTION persis seperti ORIGINAL_CONTENT.
- requestedTopic hanya referensi topik. Jangan menjadikannya judul mentah.
- Pertahankan gaya natural ORIGINAL_CONTENT sebanyak mungkin.
- Source hanya untuk FILTER/VERIFIKASI fakta, bukan untuk menentukan struktur atau jumlah slide.
- Jangan menambah URL/sumber apa pun.
- Untuk copy faktual yang tetap dipakai, sertakan claim dengan sourceId + evidence PERSIS dari FACT_BANK.
- Satu claim hanya boleh memakai satu sourceId/evidence. Jangan gabungkan beberapa sumber menjadi kesimpulan baru.
- Jika fakta ORIGINAL_CONTENT tidak didukung, ubah hanya copy faktual itu menjadi fakta terdekat yang benar-benar didukung, atau menjadi copy non-faktual yang tetap berguna. Jangan mengarang.
- Hook, pertanyaan, transisi, CTA, dan saran non-faktual boleh tanpa claim.
- Setiap slide wajib tetap memiliki title dan minimal body atau points yang bermakna.
- Title, body, dan points dalam satu slide harus saling melengkapi. Jangan mengulang kalimat atau ide yang sama di field berbeda.
- Dilarang slide kosong, filler, metadata website, byline/contributor/newsletter, judul hanya topik mentah, atau "Lanjut baca tentang ...".
- Jangan mengubah hashtag, focus, metadata angle/tool, atau struktur di luar slides.
- Jangan membuat angka/nama/tanggal/manfaat/sebab-akibat baru.

Untuk setiap claim gunakan field key persis:
slide:<index>:title
slide:<index>:body
slide:<index>:point:<pointIndex>
index dimulai dari 0.
claim.text harus sama persis dengan copy field yang didukung.

FACT_BANK (hanya dari URL yang diberikan user):
${JSON.stringify(bank)}

ORIGINAL_CONTENT:
${JSON.stringify(base)}
${errors.length ? `\nERROR VERIFIKASI SEBELUMNYA YANG HARUS DIPERBAIKI:\n- ${errors.join('\n- ')}` : ''}

Kembalikan HANYA JSON:
{"slides":[{"section":"...","title":"...","body":"...","points":[],"claims":[{"field":"slide:0:body","text":"...","sourceId":"source-1","evidence":"..."}]}]}`;
}

function parseJsonResponse(response) {
  const raw = response?.choices?.[0]?.message?.content;
  if (!raw) throw new Error('Verifier sumber tidak mengembalikan konten.');
  return JSON.parse(raw);
}

async function generateFilteredContent({ content, previousTopics = [], options = {}, sources = [], client }) {
  const base = await content.generateContent(previousTopics, {
    ...options,
    useSources: false,
    skipCopyValidation: true,
    sourceContext: '',
    sources: []
  }, client);

  if (!Array.isArray(base?.slides) || !base.slides.length) {
    throw Object.assign(new Error('Konten normal tidak memiliki slide terstruktur untuk diverifikasi sumber.'), { status: 422 });
  }

  const topic = options.requestedTopic || options.mainTopic || base.topic || '';
  const bank = extractFactBank(sources, topic);
  if (!bank.length) throw Object.assign(new Error('Sumber tidak memiliki fakta yang layak untuk memverifikasi konten.'), { status: 422 });

  const openai = client || new OpenAI({ apiKey: config.aiApiKey, baseURL: config.aiBaseUrl });
  let errors = [];
  for (let attempt = 1; attempt <= MAX_VERIFY_ATTEMPTS; attempt += 1) {
    const response = await openai.chat.completions.create({
      model: config.aiModel,
      messages: [
        { role: 'system', content: 'Anda memfilter fakta carousel. Sumber hanya untuk verifikasi fakta; jangan mengganti struktur konten.' },
        { role: 'user', content: verifierPrompt({ base, bank, topic, format: options.contentFormat, errors }) }
      ],
      response_format: { type: 'json_object' }
    });
    let candidate;
    try { candidate = parseJsonResponse(response); }
    catch (error) { errors = [`JSON verifier tidak valid: ${error.message}`]; continue; }

    const checked = validateVerifiedContent(base, candidate, {
      contentService: content,
      format: options.contentFormat,
      manualTopic: options.topicSource === 'manual' ? options.requestedTopic : '',
      sources
    });
    if (!checked.errors.length) return checked.content;
    errors = checked.errors;
  }

  throw Object.assign(new Error(`Konten tidak lolos filter fakta sumber: ${errors[0] || 'verifikasi gagal'}`), {
    status: 422,
    validationErrors: errors
  });
}

